<#
  Build GhostReel: stripped libVLC (from VLC source) + overlay player.
  Usage:
    .\build.ps1              full build (libvlc if needed, app, dist)
    .\build.ps1 -AppOnly     rebuild app + dist only
    .\build.ps1 -FullPlugins dist with all plugins (module discovery pass)
#>
param([switch]$AppOnly, [switch]$FullPlugins, [switch]$RebuildLibvlc)
$ErrorActionPreference = 'Stop'
$root   = $PSScriptRoot
$image  = 'ghostreel-build'
$volume = 'ghostreel-vlc-work'

docker build -t $image "$root\docker"
if ($LASTEXITCODE) { throw 'docker build failed' }

function Invoke-InContainer([string]$cmd) {
    docker run --rm -v "${volume}:/work" -v "${root}:/src" -e "FULL_PLUGINS=$([int]$FullPlugins.IsPresent)" $image bash -c $cmd
    if ($LASTEXITCODE) { throw "container step failed: $cmd" }
}

if (-not $AppOnly) {
    $pre = if ($RebuildLibvlc) { 'rm -rf /work/install /work/vlc-*/win64 && ' } else { '' }
    Invoke-InContainer "${pre}test -f /work/install/bin/libvlc.dll || bash /src/scripts/build-libvlc.sh"
}
Invoke-InContainer 'bash /src/scripts/build-app.sh && bash /src/scripts/prune-plugins.sh'

# plugins.dat cache must be generated by a Windows binary -> run on host
$dist = Join-Path $root 'dist'
$gen  = Join-Path $dist 'vlc-cache-gen.exe'
if (Test-Path $gen) {
    & $gen (Join-Path $dist 'plugins')
    Remove-Item $gen
}
$size = (Get-ChildItem $dist -Recurse -File | Measure-Object Length -Sum).Sum / 1MB
"dist ready: {0:N1} MB  ->  $dist\GhostReel.exe" -f $size
